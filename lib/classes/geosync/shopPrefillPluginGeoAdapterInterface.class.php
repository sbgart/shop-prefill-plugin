<?php

/**
 * Адаптер к стороннему плагину выбора города.
 *
 * Каждый метод обязан быть безопасным при отсутствии чужого плагина: реализации
 * проверяют `class_exists()` и не выбрасывают наружу. Оркестратор не знает ничего
 * о внутренностях cityselect или regions — только этот контракт.
 */
interface shopPrefillPluginGeoAdapterInterface
{
    /**
     * Идентификатор для маркеров и логов: 'cityselect', 'regions'.
     */
    public function getId(): string;

    /**
     * Плагин установлен, включён на этой витрине и интеграция с ним разрешена настройкой.
     */
    public function isAvailable(): bool;

    /**
     * Что сейчас лежит в собственном хранилище чужого плагина — куки у cityselect,
     * сессионная локация у regions. Не `order.region`: туда пишет и ядро (P2).
     *
     * Пустой объект означает вакуум, который плагин вправе занять (правило G1).
     */
    public function getCurrent(): shopPrefillPluginGeoTarget;

    /**
     * Можно ли подставить этот город, ничего больше не ломая.
     *
     * Здесь стоят стоп-условия: у cityselect — настроенное администратором правило
     * перехода на другую витрину, у regions — город, привязанный к чужой витрине или
     * отсутствующий в его базе. В обоих случаях подстановка либо потребовала бы перехода,
     * либо не подействовала бы вовсе.
     */
    public function canApply(shopPrefillPluginGeoTarget $target): bool;

    /**
     * Предложить покупателю перейти на витрину своего города — вместо молчания там,
     * где `canApply()` отказал из-за чужой витрины.
     *
     * Пишем не в «выбор покупателя», а в слот «результат определения» чужого плагина:
     * его окно показывается и называет наш город вместо догадки по IP, а переход
     * выполняет он сам и только по клику человека (правило G4).
     *
     * Причину отказа `canApply()` наружу не выносим намеренно: причин три (пустая цель,
     * города нет в базе плагина, город на другой витрине), а предлагать нужно только
     * в третьей — адаптер решает это сам, оркестратору знать незачем.
     *
     * Возвращает false, если предложить нечего или не через что.
     */
    public function propose(shopPrefillPluginGeoTarget $target): bool;

    /**
     * Снять наше предложение. Вызывается при отзыве согласия вместе с `forget()`:
     * у предложения нет записи в `applied`, поэтому само оно не очистится.
     */
    public function forgetProposal(): void;

    /**
     * Записать город штатным механизмом чужого плагина. Возвращает false, если запись
     * не состоялась (чужой код бросил исключение, город не найден и т.п.).
     */
    public function apply(shopPrefillPluginGeoTarget $target): bool;

    /**
     * Стереть город, если там лежит именно наша запись. Вызывается при отзыве согласия:
     * иначе город прошлого покупателя останется в шапке следующему за этим компьютером.
     * Город, который покупатель выбирал сам, не трогаем — он не наш.
     */
    public function forget(shopPrefillPluginGeoTarget $applied): void;
}
